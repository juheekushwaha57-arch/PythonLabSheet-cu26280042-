# 30. Write a program to perform all basic set operations
# (union, intersection, difference, symmetric difference) in one program.
s1 = {1, 2, 3, 4}
s2 = {3, 4, 5, 6}

print("Union:", s1 | s2)
print("Intersection:", s1 & s2)
print("Difference:", s1 - s2)
print("Symmetric difference:", s1 ^ s2)

